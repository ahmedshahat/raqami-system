// بعض أوصاف أنواع الحسابات في النسخة الأصلية كانت إنجليزية وطويلة.
// عند وجود وصف إنجليزي نعرض شرحًا عربيًا مختصرًا مشتقًا من اسم الحساب المترجم.
foreach ($translations as $key => $value) {
    if (str_ends_with($key, '_desc') && preg_match('/[A-Za-z]/', strip_tags((string) $value))) {
        $name_key = substr($key, 0, -5);
        if (! empty($translations[$name_key])) {
            $translations[$key] = 'يُستخدم هذا الحساب لتسجيل ومتابعة '.$translations[$name_key].'.';
        }
    }
}

return $translations;
